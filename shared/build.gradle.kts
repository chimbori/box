// Bundles src/commonMain/yaml/*.yaml into one Kotlin constant per file, so every platform gets the same data without resource loading.
abstract class GenerateBundledYaml : DefaultTask() {
  @get:InputDirectory
  abstract val yamlDir: DirectoryProperty

  @get:OutputDirectory
  abstract val outputDir: DirectoryProperty

  @TaskAction
  fun generate() {
    val yamlFiles = yamlDir.get().asFile.listFiles { f -> f.extension == "yaml" }!!.sortedBy { it.name }
    val constants = yamlFiles.joinToString("\n") { f ->
      val constName = f.nameWithoutExtension.uppercase()
      // Escape "$" so Kotlin raw strings do not treat YAML text as templates.
      val text = f.readText().replace("$", "\${'$'}")
      "  const val $constName = \"\"\"\n$text\"\"\"\n"
    }
    val outFile = outputDir.get().asFile.resolve("com/chimbori/box/data/BundledYaml.kt")
    outFile.parentFile.mkdirs()
    outFile.writeText(
      "// Generated by generateBundledYaml from src/commonMain/yaml. Do not edit.\n" +
        "package com.chimbori.box.data\n\ninternal object BundledYaml {\n$constants}\n"
    )
  }
}

val generateBundledYaml = tasks.register<GenerateBundledYaml>("generateBundledYaml") {
  yamlDir.set(layout.projectDirectory.dir("src/commonMain/yaml"))
  outputDir.set(layout.buildDirectory.dir("generated/yaml/commonMain/kotlin"))
}

tasks.matching { it.name.startsWith("compile") }.configureEach {
  dependsOn(generateBundledYaml)
}

